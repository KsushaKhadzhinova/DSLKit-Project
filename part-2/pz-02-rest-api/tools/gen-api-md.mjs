const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const table = (header, rows) => [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`)].join('\n');

const refName = (ref) => ref.split('/').pop();

// A schema as one short phrase: its type, limits, allowed values and default.
export const describeSchema = (schema, t) => {
  if (!schema) return '';
  if (schema.$ref) return refName(schema.$ref);
  if (schema.type === 'array') return `${t.arrayOf} ${describeSchema(schema.items, t)}`;
  const parts = [schema.format ? `${schema.type} (${schema.format})` : (schema.type ?? 'object')];
  if (schema.maxLength !== undefined) parts.push(`${t.upTo} ${schema.maxLength} ${t.chars}`);
  if (schema.minimum !== undefined) parts.push(`${t.from} ${schema.minimum}`);
  if (schema.maximum !== undefined) parts.push(`${t.to} ${schema.maximum}`);
  if (schema.enum) parts.push(`${t.oneOf}: ${schema.enum.map((v) => `\`${v}\``).join(', ')}`);
  if (schema.default !== undefined) parts.push(`${t.defaultIs} \`${schema.default}\``);
  if (schema.readOnly) parts.push(t.readOnly);
  return parts.join(', ');
};

const schemaRows = (schema, t) =>
  Object.entries(schema.properties ?? {}).map(([name, prop]) => [`\`${name}\``, (schema.required ?? []).includes(name) ? t.yes : t.no, describeSchema(prop, t)]);

const bodyName = (content, t) => {
  const schema = content?.['application/json']?.schema;
  if (!schema) return '';
  if (schema.$ref) return refName(schema.$ref);
  if (schema.type === 'object' && schema.properties?.data) return `{ data: ${t.arrayOf} ${describeSchema(schema.properties.data.items, t)}, meta }`;
  return describeSchema(schema, t);
};

const operationLines = (method, route, op, spec, t) => {
  const lines = [`### ${method.toUpperCase()} \`${spec.servers?.[0]?.url ?? ''}${route}\``, '', t.translate(op.summary), ''];
  if (op.parameters?.length) {
    lines.push(`**${t.parameters}**`, '');
    lines.push(
      table(
        [t.cols.name, t.cols.where, t.cols.rule, t.cols.note],
        op.parameters.map((p) => [`\`${p.name}\``, t.where[p.in] ?? p.in, describeSchema(p.schema, t), p.description ? t.translate(p.description) : '']),
      ),
      '',
    );
  }
  if (op.requestBody) {
    const ref = op.requestBody.content['application/json'].schema;
    lines.push(`**${t.body}** (\`application/json\`, ${refName(ref.$ref)})`, '');
    const schema = spec.components.schemas[refName(ref.$ref)];
    lines.push(table([t.cols.field, t.cols.required, t.cols.rule], schemaRows(schema, t)), '');
  }
  const rows = Object.entries(op.responses).map(([code, res]) => [code === 'default' ? t.other : code, t.translate(res.description), bodyName(res.content, t)]);
  lines.push(`**${t.responses}**`, '', table([t.cols.code, t.cols.meaning, t.cols.body], rows), '');
  return lines;
};

// Pure function: the document and a language in, the Markdown text out.
export const renderApiMd = (spec, lang, base = '/api') => {
  const t = TEXT[lang];
  const lines = [`# ${t.title}`, '', t.intro(spec, base), '', `## ${t.endpoints}`, ''];
  for (const [route, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) if (item[method]) lines.push(...operationLines(method, route, item[method], spec, t));
  }
  lines.push(`## ${t.schemas}`, '');
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    lines.push(`### ${name}`, '');
    if (schema.properties) lines.push(table([t.cols.field, t.cols.required, t.cols.rule], schemaRows(schema, t)), '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
};

// Asks a real server (started on a free port) for its OpenAPI document.
export const fetchSpec = async () => {
  const server = createApp().listen(0);
  await new Promise((resolve) => server.once('listening', resolve));
  try {
    const res = await fetch(`http://127.0.0.1:${server.address().port}/api/openapi.json`);
    return await res.json();
  } finally {
    server.closeAllConnections();
    await new Promise((resolve) => server.close(resolve));
  }
};

export const FILES = { en: 'API.generated.en.md', ru: 'API.generated.ru.md' };

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const spec = await fetchSpec();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const lang of ['en', 'ru']) {
    const file = path.join(dir, FILES[lang]);
    const text = renderApiMd(spec, lang);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
        console.error(`${FILES[lang]} is out of date, run: node tools/gen-api-md.mjs`);
        stale = true;
      }
    } else {
      fs.writeFileSync(file, text);
      console.log(`Wrote ${FILES[lang]}`);
    }
  }
  if (stale) process.exitCode = 1;
}
