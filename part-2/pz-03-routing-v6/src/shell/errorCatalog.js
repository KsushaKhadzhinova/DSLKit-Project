// Picks the page for an error caught by a boundary: a failed download of the code or data is a network problem, everything else is a 500.
const NETWORK_TEXT = /dynamically imported module|loading chunk|loading css chunk|failed to fetch|networkerror|load failed|importing a module script/i;
export const kindOfError = (error) => (NETWORK_TEXT.test(String(error?.message ?? error ?? '')) ? 'network' : '500');
