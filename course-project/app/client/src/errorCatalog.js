// The page for a failure caught by an axios call: no answer at all is a network problem, a status picks its own page.
// Statuses without a page of their own (400, 409, 429) return null: the message from the server is already specific.
export const kindOfFailure = (error) => {
  if (!error?.response) return 'network';
  const status = error.response.status;
  if (status === 401 || status === 403 || status === 404) return String(status);
  return status >= 500 ? '500' : null;
};

// The page for an error caught by a React boundary: a failed download of code is a network problem, the rest is a 500.
const NETWORK_TEXT = /dynamically imported module|loading chunk|loading css chunk|failed to fetch|networkerror|load failed|importing a module script/i;
export const kindOfCrash = (error) => (NETWORK_TEXT.test(String(error?.message ?? error ?? '')) ? 'network' : '500');
