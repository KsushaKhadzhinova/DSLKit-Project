from rg_common import w
from bsc_data import PERSPECTIVES, GOALS, LINKS, KPIS, INITIATIVES

CODE = {g[0]: g for g in GOALS}
STRENGTH = {0.25: "очень слабое", 0.5: "слабое", 1: "нормальное", 2: "сильное", 4: "очень сильное"}


def goals_table():
    rows = ["| Код | Перспектива | Цель | Ответственный |", "|---|---|---|---|"]
    for g in GOALS:
        rows.append(f"| {g[0]} | {PERSPECTIVES[g[1]]} | {g[2].replace(chr(10), ' ')} | {g[3]} |")
    return "\n".join(rows)


def kpi_table():
    rows = ["| № (цель) | Показатель, единица | Тип, период | Целевое значение |", "|---|---|---|---|"]
    for k in KPIS:
        rows.append(f"| П{k[0]} ({k[1]}) | {k[2]}, {k[3]} | {k[4]}, {k[5]} | {k[6]} |")
    return "\n".join(rows)


def process_table():
    rows = ["| № | Показатель | Процесс модели |", "|---|---|---|"]
    names = {"A1": "A1 Регистрация и управление доступом", "A2": "A2 Написание и проверка DSL-кода",
             "A3": "A3 Построение и экспорт диаграммы", "A4": "A4 Хранение проектов и администрирование"}
    for k in KPIS:
        rows.append(f"| П{k[0]} | {k[2]} | {names[k[7]]} |")
    return "\n".join(rows)


def init_table():
    rows = ["| № | Мероприятие | Цели | Срок | Ответственный |", "|---|---|---|---|---|"]
    for i, m in enumerate(INITIATIVES, 1):
        rows.append(f"| {i} | {m[0]} | {m[1]} | {m[2]} | {m[3]} |")
    return "\n".join(rows)


def links_table():
    rows = ["| Причина | Следствие | Сила влияния |", "|---|---|---|"]
    for a, b, s in LINKS:
        rows.append(f"| {a}. {CODE[a][2].replace(chr(10), ' ')} | {b}. {CODE[b][2].replace(chr(10), ' ')} | {STRENGTH[s]} |")
    return "\n".join(rows)


n = len(KPIS)
per = [sum(1 for k in KPIS if CODE[k[1]][1] == p) for p in range(4)]
share = [round(100 * x / n) for x in per]
nonfin = round(100 * (n - per[0]) / n)

