"""Диаграммы ЛР2 (МБП, BPMN) для процесса «Написание и проверка DSL-кода» сервиса DSLKit.
Запуск: python generate_lr2.py"""
import os
from bpmn import Bpmn

OUT = os.path.dirname(os.path.abspath(__file__))


def main_process():
    d = Bpmn("BPMN-1", 1700, 880)
    d.pool(40, 30, 1620, 60, "Пользователь", collapsed=True)
    d.pool(40, 170, 1620, 520, "DSLKit: написание и проверка DSL-кода")
    d.lane(74, 170, 1586, 250, "Веб-редактор")
    d.lane(74, 420, 1586, 270, "Модуль проверки")
    d.pool(40, 780, 1620, 60, "Сервис рендеринга Kroki", collapsed=True)

    d.event(150, 295, "start", "message", "Пользователь\nоткрыл\nредактор")
    d.task(200, 260, 130, 70, "Показать нотации\nи шаблоны", "send")
    d.event(400, 295, "inter", "message", "Выбрана нотация")
    d.task(460, 260, 130, 70, "Создать заготовку\nкода")
    d.data(525, 200, "Заготовка кода")
    d.task(640, 260, 130, 70, "Принять код\nпользователя", "receive")
    d.event(705, 330, "inter", "timer", "Прошло\n30 минут", "right")
    d.gate(850, 295, "xor", "Лимит тарифа\nпревышен?", "below")
    d.task(910, 185, 130, 60, "Предложить\nтариф Pro", "send")
    d.event(1085, 215, "end", "none", "Ввод отклонён", "below")
    d.task(940, 260, 130, 70, "Отправить код\nна проверку")
    d.sub(940, 495, 130, 80, "Проверить код")
    d.gate(1200, 535, "xor", "Код допустим?", "above")
    d.task(1135, 590, 130, 55, "Сформировать\nсписок ошибок")
    d.data(1305, 625, "Список ошибок")
    d.task(1035, 335, 130, 60, "Показать ошибки\nи подсказки", "send")
    d.task(1300, 505, 130, 60, "Сохранить проверенный\nкод в проекте")
    d.data(1400, 625, "База проектов", "db")
    d.event(1540, 535, "end", "message", "Код передан\nна построение", "above")
    d.task(640, 500, 130, 60, "Сохранить\nчерновик")
    d.data(705, 625, "База проектов", "db")
    d.event(850, 530, "end", "none", "Черновик\nсохранён", "below")

    # потоки управления
    d.flow([(168, 295), (200, 295)])
    d.flow([(330, 295), (382, 295)])
    d.flow([(418, 295), (460, 295)])
    d.flow([(590, 295), (640, 295)])
    d.flow([(770, 295), (826, 295)])
    d.flow([(850, 271), (850, 215), (910, 215)], label="Да", lx=868, ly=232, align="left")
    d.flow([(874, 295), (940, 295)], label="Нет", lx=907, ly=282)
    d.flow([(1040, 215), (1067, 215)])
    d.flow([(1005, 330), (1005, 495)])
    d.flow([(1070, 535), (1176, 535)])
    d.flow([(1200, 559), (1200, 590)], label="Нет", lx=1212, ly=575, align="left")
    d.flow([(1224, 535), (1300, 535)], label="Да", lx=1262, ly=522)
    d.flow([(1430, 535), (1522, 535)])
    d.flow([(1135, 617), (1100, 617), (1100, 395)])
    d.flow([(1035, 365), (740, 365), (740, 330)])
    d.flow([(705, 348), (705, 500)])
    d.flow([(770, 530), (832, 530)])
    # ассоциации с объектами данных
    d.flow([(525, 260), (525, 222)], "assoc")
    d.flow([(1265, 617), (1290, 617)], "assoc")
    d.flow([(1400, 565), (1400, 602)], "assoc")
    d.flow([(705, 560), (705, 602)], "assoc")
    # потоки сообщений
    d.flow([(150, 90), (150, 277)], "msg", "Запрос на создание\nдиаграммы", 158, 130, "left")
    d.flow([(265, 260), (265, 90)], "msg", "Список нотаций\nи шаблонов", 273, 130, "left")
    d.flow([(400, 90), (400, 277)], "msg", "Выбранная\nнотация", 408, 130, "left")
    d.flow([(670, 90), (670, 260)], "msg", "Код диаграммы", 678, 130, "left")
    d.flow([(975, 185), (975, 90)], "msg", "Предложение перейти\nна тариф Pro", 983, 130, "left")
    d.flow([(1150, 335), (1150, 90)], "msg", "Ошибки и подсказки", 1158, 130, "left")
    d.flow([(1540, 553), (1540, 780)], "msg", "Проверенный DSL-код", 1548, 740, "left")
    d.save(os.path.join(OUT, "01_BPMN_написание_и_проверка_кода"))


def sub_process():
    d = Bpmn("BPMN-2", 1300, 640)
    d.pool(40, 60, 1220, 520, "Проверка кода")
    d.lane(74, 60, 1186, 520, "Модуль проверки")
    d.event(150, 310, "start", "none", "Получен код\nна проверку", "below")
    d.gate(240, 310, "and", "", "below")
    d.task(320, 200, 150, 70, "Проверить\nсинтаксис", "service")
    d.task(320, 350, 150, 70, "Проверить правила\nнотации", "service")
    d.gate(560, 310, "and", "", "below")
    d.gate(690, 310, "xor", "Ошибки\nнайдены?", "below")
    d.task(780, 170, 150, 70, "Сформировать\nсписок ошибок", "service")
    d.data(855, 310, "Список ошибок")
    d.event(1060, 205, "end", "none", "Код отклонён", "below")
    d.event(780, 430, "end", "none", "Код принят", "below")

    d.flow([(168, 310), (216, 310)])
    d.flow([(240, 286), (240, 235), (320, 235)])
    d.flow([(240, 334), (240, 385), (320, 385)])
    d.flow([(470, 235), (560, 235), (560, 286)])
    d.flow([(470, 385), (560, 385), (560, 334)])
    d.flow([(584, 310), (666, 310)])
    d.flow([(690, 286), (690, 205), (780, 205)], label="Да", lx=702, ly=192, align="left")
    d.flow([(690, 334), (690, 430), (762, 430)], label="Нет", lx=702, ly=400, align="left")
    d.flow([(930, 205), (1042, 205)])
    d.flow([(855, 240), (855, 288)], "assoc")
    d.save(os.path.join(OUT, "02_BPMN_подпроцесс_проверка_кода"))


if __name__ == "__main__":
    main_process()
    sub_process()
    print("done")
