// Makes docs/eval/descriptions.ru.json and descriptions.en.json from the hand-written entries in desc-*.mjs.
// Run: node docs/eval/src/make-descriptions.mjs
import { writeFileSync } from 'node:fs';
import { BPMN } from './desc-bpmn.mjs';
import { DFD } from './desc-dfd.mjs';
import { ERD } from './desc-erd.mjs';
import { GOST } from './desc-gost.mjs';
import { SEQUENCE } from './desc-sequence.mjs';

const GROUPS = [
  ['bpmn', BPMN],
  ['gost', GOST],
  ['erd', ERD],
  ['uml-sequence', SEQUENCE],
  ['dfd', DFD],
];

const problems = [];
const files = { ru: [], en: [] };
GROUPS.forEach(([notation, entries]) => {
  entries.forEach((entry, at) => {
    const [level, tags, ruText, ruEl, ruRel, enText, enEl, enRel, contested] = entry;
    [
      ['ru', ruText, ruEl, ruRel],
      ['en', enText, enEl, enRel],
    ].forEach(([lang, text, el, rel]) => {
      const ids = rel
        .split(/[\s-]+/)
        .filter(Boolean)
        .map(Number);
      if (ids.some((id) => id >= el.length)) problems.push(`${notation} #${at + 1} ${lang}: relation index out of range`);
      files[lang].push({
        id: `${lang}-${notation}-${String(at + 1).padStart(2, '0')}`,
        notation,
        level,
        tags: tags.split(' '),
        ...(contested ? { contested: true } : {}),
        text,
        el,
        rel,
      });
    });
  });
});
if (problems.length > 0) throw new Error(problems.join('\n'));

Object.entries(files).forEach(([lang, cases]) => {
  const out = {
    version: 1,
    lang,
    note: 'Hand-written by meaning of the text. See docs/eval/README.md. Generated by docs/eval/src/make-descriptions.mjs.',
    cases,
  };
  writeFileSync(new URL(`../descriptions.${lang}.json`, import.meta.url), JSON.stringify(out, null, 2) + '\n');
  const counts = Object.fromEntries(GROUPS.map(([notation]) => [notation, cases.filter((item) => item.notation === notation).length]));
  console.log(lang, cases.length, JSON.stringify(counts));
});
