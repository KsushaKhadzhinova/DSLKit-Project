import { start, sleep } from './dtf.mjs';
const OUT = 'E:/DSLKit-Project/labs/06-async-api-storage/figures';
const { b, app, open } = await start();
await app.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'light' }]);
const dt = await open('network');
const shot = (n) => dt.screenshot({ path: `${OUT}/devtools-${n}.png` });
await app.bringToFront();
await app.goto('http://localhost:5173/app/editor.html', { waitUntil: 'load' });
await sleep(1500);
await app.click('.canvas__render');
await app.waitForSelector('.canvas__remote svg', { timeout: 30000 });
await sleep(1500);
await dt.bringToFront();
await dt.mouse.click(330, 68); await dt.keyboard.type('kroki'); await sleep(900);
await dt.mouse.click(80, 201); await sleep(1200);
await shot('01-kroki-request');
await dt.mouse.click(332, 177); await sleep(900); await shot('02-kroki-payload');
await dt.mouse.click(499, 15); await sleep(1000);
await dt.mouse.click(16, 187); await sleep(800);
await dt.mouse.click(115, 209); await sleep(1000);
await shot('03-local-storage');
await app.bringToFront();
await app.evaluate(() => localStorage.clear());
await app.setRequestInterception(true);
app.on('request', (r) => (r.url().includes('kroki.io') ? r.abort('internetdisconnected') : r.continue()));
await app.reload({ waitUntil: 'load' });
await sleep(1000);
await app.click('.canvas__render');
await sleep(9000);
const el = await app.$('.canvas');
await el.screenshot({ path: `${OUT}/error-no-cache.png` });
await b.close();
