import { start, sleep } from './dtf.mjs';
const OUT = 'E:/DSLKit-Project/labs/08-frontend-testing/figures';
const { b, app, open } = await start();
await app.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: 'light' }]);
const dt = await open('sources');
const shot = (n) => dt.screenshot({ path: `${OUT}/devtools-${n}.png` });
await app.goto('http://localhost:5173/', { waitUntil: 'load' });
await sleep(2500);
await dt.bringToFront();
await dt.mouse.click(700, 400);
await dt.keyboard.down('Control'); await dt.keyboard.press('KeyP'); await dt.keyboard.up('Control'); await sleep(600);
await dt.keyboard.type('helpers.js'); await sleep(900); await dt.keyboard.press('Enter'); await sleep(1500);
await dt.mouse.click(256, 338); await sleep(700);
await shot('01-sources-breakpoint');
app.reload({ waitUntil: 'domcontentloaded' }).catch(() => {});
await sleep(4000);
await dt.bringToFront();
await shot('02-sources-paused');
await dt.mouse.click(1420, 40); await sleep(1200);
await shot('03-sources-step-over');
await dt.mouse.click(1448, 40); await sleep(1200);
await shot('04-sources-step-into');
await b.close();
