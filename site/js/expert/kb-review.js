// A rule with a priority gives a recommendation; "lines" names the fact with the line numbers to show; {name} in a text is replaced by a fact.
const rule = (id, conditions, cf, priority, lines, reason, text) => ({
  id,
  if: conditions,
  then: { fact: `advice:${id}`, cf },
  priority,
  lines,
  reason,
  text,
});
const yes = (fact) => ({ fact });
const over = (fact, value) => ({ fact, op: '>', value });

