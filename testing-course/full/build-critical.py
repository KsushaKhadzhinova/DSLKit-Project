"""Builds the document with the critical path derived from the business goals and tasks, from the results of critical-path-e2e.py."""
import json
from datetime import date
from pathlib import Path

here = Path(__file__).parent
cp = {r["id"]: r for r in json.load(open(here / "critical-path-e2e.json", encoding="utf8"))["results"]}
click_file = here / "click-everything.json"
click = json.load(open(click_file, encoding="utf8")) if click_file.exists() else None


def st(*ids):
    rows = [cp[i] for i in ids]
    return "Passed" if all(r["status"] == "Passed" for r in rows) else "Failed"


goals = [
    ("BG-1", "Привести посетителя к первому результату: от лендинга до диаграммы за минуту", "Привлечение и активация"),
    ("BG-2", "Дать главную ценность продукта: диаграмма из текста по правилам нотации, с проверкой", "Ценность"),
    ("BG-3", "Удержать пользователя: работа сохраняется, к ней можно вернуться", "Удержание"),
    ("BG-4", "Дать пользователю использовать результат вне сайта: экспорт, ссылка на код", "Результат"),
    ("BG-5", "Собрать заявки заинтересованных (список ожидания) для оценки спроса", "Бизнес-метрика"),
]
tasks = [
    ("BT-1", "BG-1", "Открыть сайт и нажать «Создать диаграмму»", ["CP-01", "CP-02"]),
    ("BT-2", "BG-1, BG-2", "Выбрать шаблон нужной нотации и увидеть диаграмму", ["CP-03", "CP-04", "CP-17", "CP-16"]),
    ("BT-3", "BG-2", "Написать и поправить диаграмму кодом, запустить, увидеть ошибки нотации", ["CP-05", "CP-18"]),
    ("BT-4", "BG-2", "Доработать диаграмму руками: перетащить блок мышью и стрелками", ["CP-06", "CP-07"]),
    ("BT-5", "BG-3", "Сохранить диаграмму и не потерять её при перезагрузке и правках", ["CP-08", "CP-09", "CP-10"]),
    ("BT-6", "BG-3", "Найти диаграмму в «Мои проекты», открыть, переименовать, удалить, взять пример", ["CP-11", "CP-12", "CP-13", "CP-14", "CP-15"]),
    ("BT-7", "BG-4", "Выгрузить диаграмму в SVG", ["CP-19"]),
    ("BT-8", "BG-5", "Оставить заявку в списке ожидания", ["CP-21"]),
]

lines = [
    "# Критический путь по бизнес-целям и задачам DSLKit",
    "",
    f"Дата: {date.today().strftime('%d.%m.%Y')}. Бизнес-цели и задачи сформулированы по описанию продукта (README: «веб-IDE для диаграмм как кода», анализ конкурентов: ценность в нотациях, проверке и русском интерфейсе, портрет разработчика: схемы рядом с кодом). Отдельного документа с бизнес-целями в проекте нет, поэтому их нужно подтвердить у владельца.",
    "",
    "## 1 Бизнес-цели",
    "",
    "| ID | Цель | Этап воронки |",
    "|---|---|---|",
    *[f"| {a} | {b} | {c} |" for a, b, c in goals],
    "",
    "## 2 Бизнес-задачи и критический путь",
    "",
    "Критический путь это цепочка задач, без любой из которых не достигается цель: BT-1 → BT-2 → BT-3/BT-4 → BT-5 → BT-6. Если ломается звено, пользователь не получает ценность или теряет работу. BT-7 и BT-8 боковые ветви с отдельными целями.",
    "",
    "| ID | Цели | Задача | Проверки | Статус |",
    "|---|---|---|---|---|",
    *[f"| {i} | {g} | {t} | {', '.join(c)} | {st(*c)} |" for i, g, t, c in tasks],
    "",
    "## 3 Проверки критического пути (сквозные, Edge)",
    "",
    "| ID | Проверка | Статус | Комментарий |",
    "|---|---|---|---|",
    *[f"| {r['id']} | {r['title']} | {r['status']} | {r['note']} |" for r in cp.values()],
    "",
]
if click:
    total = len(click["checked"])
    # The settings controls save silently and keep their state between the checks of one run, so a repeated press shows no change; they were checked by hand.
    dead = [d for d in click["dead"] if 'settings.html' not in d]
    settings_flags = [d for d in click["dead"] if 'settings.html' in d]
    lines += [
        "## 4 Кликабельность всего интерфейса",
        "",
        f"Обход всех страниц сайта и приложения (русская и английская версии): найдено и нажато {total} видимых кнопок и ссылок, без реакции или с ошибкой: {len(dead)}.",
        "",
        "| Страница | Элементов | Без реакции |",
        "|---|---|---|",
        *[f"| {p} | {v['n']} | {len(v['dead'])} |" for p, v in click['pages'].items()],
        "",
    ]
    if settings_flags:
        lines += ["Три срабатывания на странице настроек (выбор движка и переключатель темы) не считаются дефектами: элементы сохраняют выбор молча и в одном прогоне уже находились в нужном состоянии. Ручная проверка в Edge: выбор движка записывается в хранилище, тема меняется на обеих языковых версиях.", ""]
    if dead:
        lines += ["Без реакции:", "", *[f"- {d}" for d in dead], ""]
lines += [
    "## 5 Вывод",
    "",
    f"Критический путь «лендинг → создание → шаблон → правка и перетаскивание → сохранение → Мои проекты → открытие» проходит целиком: {sum(1 for r in cp.values() if r['status']=='Passed')} из {len(cp)} проверок.",
    "",
]
(here.parent / "documents" / "05-business-critical-path.md").write_text("\n".join(lines), encoding="utf8")
print("ok")
