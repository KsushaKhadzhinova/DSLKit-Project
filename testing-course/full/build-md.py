def kind(rows, k):
    return [r for r in rows if r["kind"] == k]


def counts(rows):
    p = sum(1 for r in rows if r["status"] == "Passed")
    return len(rows), p, len(rows) - p


def table(rows):
    out = ["| ID | Проверка | Статус | Комментарий |", "|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['id']} | {r['title']} | {r['status']} | {r['note'] or ''} |")
    return "\n".join(out)


